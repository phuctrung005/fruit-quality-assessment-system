import os
import shutil
import random

# Đường dẫn đến thư mục dữ liệu gốc
data_dir = '/content/Dataset/'
original_train_dir = os.path.join(data_dir, 'Train')

# Đường dẫn đến các thư mục huấn luyện và xác thực mới
new_train_dir = os.path.join(data_dir, 'Train_Split')
new_val_dir = os.path.join(data_dir, 'Validation_Split')

# Xóa các thư mục cũ nếu chúng tồn tại để tránh lỗi
if os.path.exists(new_train_dir):
    shutil.rmtree(new_train_dir)
if os.path.exists(new_val_dir):
    shutil.rmtree(new_val_dir)

# Tạo các thư mục mới
os.makedirs(new_train_dir, exist_ok=True)
os.makedirs(new_val_dir, exist_ok=True)

print(f"Bắt đầu chia dữ liệu từ '{original_train_dir}'...")

# Lặp qua từng lớp (thư mục con) trong tập huấn luyện gốc
for class_name in os.listdir(original_train_dir):
    class_path = os.path.join(original_train_dir, class_name)
    if os.path.isdir(class_path):
        # Tạo thư mục cho lớp trong các tập mới
        os.makedirs(os.path.join(new_train_dir, class_name), exist_ok=True)
        os.makedirs(os.path.join(new_val_dir, class_name), exist_ok=True)

        # Lấy danh sách tất cả các file ảnh trong lớp
        images = [f for f in os.listdir(class_path) if f.lower().endswith(('.png', '.jpg', '.jpeg'))]
        random.shuffle(images)

        # Chia 80% cho huấn luyện, 20% cho xác thực
        train_split_size = int(0.8 * len(images))
        train_images = images[:train_split_size]
        val_images = images[train_split_size:]

        # Di chuyển các file ảnh vào thư mục mới
        for img in train_images:
            src = os.path.join(class_path, img)
            dst = os.path.join(new_train_dir, class_name, img)
            shutil.copy(src, dst)
        for img in val_images:
            src = os.path.join(class_path, img)
            dst = os.path.join(new_val_dir, class_name, img)
            shutil.copy(src, dst)

        print(f"  Lớp '{class_name}': {len(train_images)} ảnh cho huấn luyện, {len(val_images)} ảnh cho xác thực.")

print("Chia dữ liệu hoàn tất.")

import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator

# Định nghĩa các tham số (lấy lại từ cell 61b95803 để đảm bảo tính nhất quán)
IMAGE_SIZE = (224, 224)
BATCH_SIZE = 32
NUM_CLASSES = 3
data_dir = '/content/Dataset/'

# Đường dẫn đến các thư mục huấn luyện và xác thực mới đã được chia
new_train_dir = os.path.join(data_dir, 'Train_Split')
new_val_dir = os.path.join(data_dir, 'Validation_Split')

# Tạo ImageDataGenerator cho tập huấn luyện và kiểm tra/xác thực
# Tăng cường dữ liệu cho tập huấn luyện
train_datagen = ImageDataGenerator(
    rescale=1./255,
    rotation_range=20,
    width_shift_range=0.2,
    height_shift_range=0.2,
    shear_range=0.2,
    zoom_range=0.2,
    horizontal_flip=True,
    fill_mode='nearest'
)

# Không tăng cường dữ liệu cho tập xác thực và kiểm tra, chỉ chuẩn hóa
val_test_datagen = ImageDataGenerator(rescale=1./255)

# Tải dữ liệu từ thư mục huấn luyện mới
print("Đang tải dữ liệu huấn luyện (đã chia)...")
train_generator = train_datagen.flow_from_directory(
    new_train_dir,
    target_size=IMAGE_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='categorical'
)

# Tải dữ liệu từ thư mục xác thực mới
print("Đang tải dữ liệu xác thực...")
validation_generator = val_test_datagen.flow_from_directory(
    new_val_dir,
    target_size=IMAGE_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='categorical',
    shuffle=False # Không xáo trộn tập xác thực
)

# Tải dữ liệu từ thư mục kiểm tra (không thay đổi)
print("Đang tải dữ liệu kiểm tra (không thay đổi)...")
test_generator = val_test_datagen.flow_from_directory(
    os.path.join(data_dir, 'Test'),
    target_size=IMAGE_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='categorical',
    shuffle=False # Không xáo trộn tập kiểm tra
)

print("Các Generator đã được thiết lập thành công.")
print(f"Số lớp được phát hiện: {train_generator.num_classes}")
print(f"Các nhãn tương ứng với số thứ tự: {train_generator.class_indices}")

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten, Dense, Dropout

# Khởi tạo mô hình Sequential
model = Sequential([
    # Lớp Conv2D đầu tiên
    Conv2D(32, (3, 3), activation='relu', input_shape=(IMAGE_SIZE[0], IMAGE_SIZE[1], 3)),
    MaxPooling2D((2, 2)),

    # Lớp Conv2D thứ hai
    Conv2D(64, (3, 3), activation='relu'),
    MaxPooling2D((2, 2)),

    # Lớp Conv2D thứ ba
    Conv2D(128, (3, 3), activation='relu'),
    MaxPooling2D((2, 2)),

    # Lớp Flatten để chuyển đổi đầu ra từ các lớp tích chập thành vector 1D
    Flatten(),

    # Lớp Dense (Fully Connected) với Dropout để giảm overfitting
    Dense(512, activation='relu'),
    Dropout(0.5),

    # Lớp đầu ra với số lượng neuron bằng số lớp phân loại và hàm kích hoạt softmax
    Dense(NUM_CLASSES, activation='softmax')
])

# Biên dịch mô hình
model.compile(
    optimizer='adam',
    loss='categorical_crossentropy',
    metrics=['accuracy']
)

# Hiển thị tóm tắt mô hình
model.summary()

from tensorflow.keras.callbacks import ModelCheckpoint, EarlyStopping

# Định nghĩa các tham số huấn luyện
EPOCHS = 50 # Số lượng epoch bạn muốn huấn luyện

# Callback để lưu lại mô hình có độ chính xác tốt nhất trên tập xác thực
checkpoint_filepath = 'best_model.weights.h5'
model_checkpoint_callback = ModelCheckpoint(
    filepath=checkpoint_filepath,
    save_weights_only=True, # Chỉ lưu trọng số của mô hình
    monitor='val_accuracy', # Giám sát độ chính xác trên tập xác thực
    mode='max',
    save_best_only=True
)

# Callback để dừng sớm quá trình huấn luyện nếu độ chính xác không cải thiện
early_stopping_callback = EarlyStopping(
    monitor='val_accuracy',
    patience=10, # Chờ 10 epoch nếu không có cải thiện thì dừng
    mode='max',
    restore_best_weights=True # Khôi phục trọng số của epoch tốt nhất
)

print("Bắt đầu huấn luyện mô hình với tập xác thực riêng biệt...")
history = model.fit(
    train_generator,
    epochs=EPOCHS,
    validation_data=validation_generator, # Đã thay đổi từ test_generator sang validation_generator
    callbacks=[model_checkpoint_callback, early_stopping_callback]
)

print("Huấn luyện hoàn tất.")

# Load the best weights
model.load_weights(checkpoint_filepath)

# Đánh giá mô hình trên tập kiểm tra
print("Đánh giá mô hình trên tập kiểm tra...")
loss, accuracy = model.evaluate(test_generator)
print(f"Test Loss: {loss:.4f}")
print(f"Test Accuracy: {accuracy:.4f}")

from sklearn.metrics import recall_score
import numpy as np

# Lấy các nhãn thực tế từ test_generator
true_labels = test_generator.classes

# Lấy các dự đoán của mô hình
predictions = model.predict(test_generator)
predicted_labels = np.argmax(predictions, axis=1)

# Tính toán Recall
# Sử dụng 'macro' average để tính toán recall cho mỗi lớp và sau đó lấy trung bình không trọng số.
# Hoặc bạn có thể dùng 'weighted' nếu muốn tính trọng số theo số lượng mẫu của mỗi lớp.
recall = recall_score(true_labels, predicted_labels, average='macro')

print(f"Test Recall (Macro): {recall:.4f}")

import matplotlib.pyplot as plt

