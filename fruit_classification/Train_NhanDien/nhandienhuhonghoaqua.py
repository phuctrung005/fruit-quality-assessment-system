# Helper function for IoU calculation
def iou(box1, box2):
    # box format: [x1, y1, x2, y2]
    x1_inter = max(box1[0], box2[0])
    y1_inter = max(box1[1], box2[1])
    x2_inter = min(box1[2], box2[2])
    y2_inter = min(box1[3], box2[3])

    inter_width = max(0.0, x2_inter - x1_inter)
    inter_height = max(0.0, y2_inter - y1_inter)
    inter_area = inter_width * inter_height

    box1_area = (box1[2] - box1[0]) * (box1[3] - box1[1])
    box2_area = (box2[2] - box2[0]) * (box2[3] - box2[1])

    union_area = float(box1_area + box2_area - inter_area)
    if union_area == 0:
        return 0.0
    return inter_area / union_area

# Custom function to convert object detection outputs to classification inputs for ConfusionMatrix
def calculate_object_detection_confusion_matrix_inputs(all_preds, all_targets, num_classes, iou_threshold=0.5, score_threshold=0.3):
    true_labels_flat = []
    pred_labels_flat = []
    # Assuming the last class index is for background
    BACKGROUND_CLASS_ID = num_classes - 1

    for img_idx in range(len(all_targets)):
        gt_boxes = all_targets[img_idx]['boxes'].cpu()
        gt_labels = all_targets[img_idx]['labels'].cpu()

        # Ensure 'boxes', 'labels', 'scores' keys exist in predictions and are not empty
        if 'boxes' not in all_preds[img_idx] or all_preds[img_idx]['boxes'].numel() == 0:
            pred_boxes = torch.empty((0, 4))
            pred_labels = torch.empty((0,), dtype=torch.int64)
            pred_scores = torch.empty((0,))
        else:
            pred_boxes = all_preds[img_idx]['boxes'].cpu()
            pred_labels = all_preds[img_idx]['labels'].cpu()
            pred_scores = all_preds[img_idx]['scores'].cpu()

        # Filter predictions by score threshold
        high_conf_preds_indices = pred_scores >= score_threshold
        pred_boxes_filtered = pred_boxes[high_conf_preds_indices]
        pred_labels_filtered = pred_labels[high_conf_preds_indices]

        matched_gt_indices = set()
        matched_pred_indices = set()

        # Iterate through ground truth boxes to find matches
        for i, gt_box in enumerate(gt_boxes):
            best_iou = -1
            best_pred_idx = -1

            for j, pred_box in enumerate(pred_boxes_filtered):
                current_iou = iou(gt_box, pred_box)
                if current_iou > best_iou:
                    best_iou = current_iou
                    best_pred_idx = j

            if best_iou >= iou_threshold and best_pred_idx not in matched_pred_indices:
                # True Positive or Misclassification
                true_labels_flat.append(gt_labels[i].item())
                pred_labels_flat.append(pred_labels_filtered[best_pred_idx].item())
                matched_gt_indices.add(i)
                matched_pred_indices.add(best_pred_idx)
            else:
                # False Negative: Ground truth not detected or poorly localized
                true_labels_flat.append(gt_labels[i].item())
                pred_labels_flat.append(BACKGROUND_CLASS_ID) # Predicted as background

        # Handle False Positives: Predictions that did not match any ground truth
        for j, pred_box in enumerate(pred_boxes_filtered):
            if j not in matched_pred_indices:
                true_labels_flat.append(BACKGROUND_CLASS_ID) # True label is background
                pred_labels_flat.append(pred_labels_filtered[j].item())

    return torch.tensor(true_labels_flat, dtype=torch.long), torch.tensor(pred_labels_flat, dtype=torch.long)


