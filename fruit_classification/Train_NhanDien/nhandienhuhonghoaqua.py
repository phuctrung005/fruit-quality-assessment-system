class COCODataset(Dataset):
    def __init__(self, root, annotation, transforms=None):
        self.root = root
        self.transforms = transforms
        self.coco = COCO(annotation)
        # Ensure imgToAnns has keys, if not, there are no annotations for images
        self.ids = list(self.coco.imgToAnns.keys())
        if not self.ids:
            # If no annotated images, try getting all image IDs if any exist in info
            self.ids = list(self.coco.imgs.keys())
            print(f"Warning: No images with annotations found. Using all {len(self.ids)} image IDs.")

        cat_ids = self.coco.getCatIds()
        self.categories = {cat['id']: cat['name'] for cat in self.coco.loadCats(cat_ids)}
        self.class_to_idx = {name: id for id, name in self.categories.items()}
        self.idx_to_class = {id: name for id, name in self.categories.items()}

    def __getitem__(self, index):
        # Own image ID
        coco_img_id = self.ids[index]

        # COCO image data
        img_data = self.coco.loadImgs(coco_img_id)[0]

        # Load image
        img_path = os.path.join(self.root, img_data['file_name'])
        img = Image.open(img_path).convert("RGB")

        # Load annotations
        ann_ids = self.coco.getAnnIds(imgIds=coco_img_id)
        anns = self.coco.loadAnns(ann_ids)

        boxes = []
        labels = []
        for ann in anns:
            x, y, w, h = ann['bbox']
            # Convert to [x_min, y_min, x_max, y_max]
            boxes.append([x, y, x + w, y + h])
            labels.append(ann['category_id'])

        # Handle case where an image might not have annotations (e.g., if a few images are unannotated in the COCO JSON)
        if len(boxes) == 0:
            # If no boxes, provide dummy data to prevent errors. Model should learn to ignore.
            boxes = torch.zeros((0, 4), dtype=torch.float32)
            labels = torch.zeros((0,), dtype=torch.int64)
            area = torch.zeros((0,), dtype=torch.float32)
            iscrowd = torch.zeros((0,), dtype=torch.int64)
        else:
            boxes = torch.as_tensor(boxes, dtype=torch.float32)
            labels = torch.as_tensor(labels, dtype=torch.int64)
            area = (boxes[:, 3] - boxes[:, 1]) * (boxes[:, 2] - boxes[:, 0])
            iscrowd = torch.zeros((len(boxes),), dtype=torch.int64)

        image_id = torch.tensor([coco_img_id])

        target = {}
        target["boxes"] = boxes
        target["labels"] = labels
        target["image_id"] = image_id
        target["area"] = area
        target["iscrowd"] = iscrowd

        if self.transforms is not None:
            img, target = self.transforms(img, target)

        return img, target

    def __len__(self):
        return len(self.ids)

# Define transforms
class Compose(object):
    def __init__(self, transforms):
        self.transforms = transforms

    def __call__(self, image, target):
        for t in self.transforms:
            image, target = t(image, target)
        return image, target

class ToTensor(object):
    def __call__(self, image, target):
        image = transforms.functional.to_tensor(image)
        return image, target

class RandomHorizontalFlip(object):
    def __init__(self, prob):
        self.prob = prob

    def __call__(self, image, target):
        if random.random() < self.prob:
            # If the image is a PIL Image, it won't have .shape
            # Need to convert to tensor first or handle flipping for PIL Image
            # For now, assuming image is already a tensor if self.transforms contains ToTensor first
            if isinstance(image, torch.Tensor):
                height, width = image.shape[-2:]
                image = image.flip(-1) # Flip horizontally
                if "boxes" in target and len(target["boxes"]) > 0:
                    bbox = target["boxes"]
                    bbox[:, [0, 2]] = width - bbox[:, [2, 0]] # Adjust x_min and x_max
                    target["boxes"] = bbox
            else:
                # If PIL Image, flip and then it will be converted to tensor later
                image = transforms.functional.hflip(image)
                # Bounding box coordinates need to be adjusted *after* PIL Image to Tensor conversion
                # For simplicity here, assuming ToTensor is always first or only transform modifying image
                # If more complex transforms are needed, consider torchvision.transforms.v2
        return image, target

def get_transform(train):
    transform_list = [ToTensor()]
    if train:
        transform_list.append(RandomHorizontalFlip(0.5))
    return Compose(transform_list)


